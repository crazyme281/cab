-- Reference / directory tables
create table public.universities (
  university_id bigint generated by default as identity primary key,
  name text not null unique
);

create table public.campuses (
  campus_id bigint generated by default as identity primary key,
  university_id bigint not null references public.universities(university_id),
  name text not null
);

create table public.faculties (
  faculty_id bigint generated by default as identity primary key,
  campus_id bigint not null references public.campuses(campus_id),
  name text not null
);

create table public.departments (
  department_id bigint generated by default as identity primary key,
  faculty_id bigint not null references public.faculties(faculty_id),
  name text not null
);

create table public.pickup_locations (
  pickup_location_id bigint generated by default as identity primary key,
  campus_id bigint not null references public.campuses(campus_id),
  name text not null
);

-- Users (extends auth.users)
create table public.users (
  user_id uuid primary key references auth.users(id),
  full_name text not null,
  email text not null unique,
  phone_number text,
  matric_number text,
  profile_image text,
  role text not null default 'user' check (role in ('user','admin')),
  status text not null default 'active' check (status in ('active','suspended','restricted','deactivated')),
  created_at timestamptz not null default now(),
  must_change_password boolean not null default false
);

create table public.categories (
  category_id bigint generated by default as identity primary key,
  name text not null unique,
  parent_category_id bigint references public.categories(category_id),
  is_active boolean not null default true
);

create table public.products (
  product_id bigint generated by default as identity primary key,
  seller_id uuid not null references public.users(user_id),
  category_id bigint not null references public.categories(category_id),
  title text not null,
  description text,
  price numeric not null,
  condition text not null default 'used_good' check (condition in ('new','used_like_new','used_good','used_fair')),
  image_url text,
  status text not null default 'available' check (status in ('available','sold')),
  created_at timestamptz not null default now(),
  approval_status text not null default 'pending' check (approval_status in ('pending','approved','rejected','hidden','removed')),
  rejection_reason text,
  featured boolean not null default false,
  view_count bigint not null default 0
);

create table public.messages (
  message_id bigint generated by default as identity primary key,
  sender_id uuid not null references public.users(user_id),
  receiver_id uuid not null references public.users(user_id),
  product_id bigint references public.products(product_id),
  message_text text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.transactions (
  transaction_id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(product_id),
  buyer_id uuid not null references public.users(user_id),
  seller_id uuid not null references public.users(user_id),
  agreed_price numeric not null,
  status text not null default 'pending' check (status in ('pending','completed','cancelled')),
  created_at timestamptz not null default now()
);

create table public.reviews (
  review_id bigint generated by default as identity primary key,
  transaction_id bigint not null references public.transactions(transaction_id),
  reviewer_id uuid not null references public.users(user_id),
  reviewee_id uuid not null references public.users(user_id),
  rating smallint not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now()
);

create table public.user_warnings (
  warning_id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(user_id),
  admin_id uuid not null references public.users(user_id),
  reason text not null,
  created_at timestamptz not null default now()
);

create table public.admin_notes (
  note_id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(user_id),
  admin_id uuid not null references public.users(user_id),
  note text not null,
  created_at timestamptz not null default now()
);

create table public.reports (
  report_id bigint generated by default as identity primary key,
  reporter_id uuid not null references public.users(user_id),
  category text not null check (category in ('fraud','harassment','prohibited_item','misleading_listing','counterfeit','spam','fake_review','other')),
  reported_user_id uuid references public.users(user_id),
  reported_product_id bigint references public.products(product_id),
  reported_review_id bigint references public.reviews(review_id),
  description text not null,
  evidence_url text,
  status text not null default 'new' check (status in ('new','under_review','resolved','dismissed')),
  assigned_admin_id uuid references public.users(user_id),
  decision text,
  resolution_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.audit_logs (
  log_id bigint generated by default as identity primary key,
  admin_id uuid references public.users(user_id),
  action text not null,
  target_type text not null,
  target_id text,
  reason text,
  previous_state jsonb,
  new_state jsonb,
  created_at timestamptz not null default now()
);

create table public.announcements (
  announcement_id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  target_type text not null default 'all' check (target_type in ('all','sellers','university','campus','user')),
  target_value text,
  created_by uuid references public.users(user_id),
  created_at timestamptz not null default now()
);

create table public.favorites (
  favorite_id bigint generated always as identity primary key,
  user_id uuid not null references public.users(user_id),
  product_id bigint not null references public.products(product_id),
  created_at timestamptz not null default now(),
  unique (user_id, product_id)
);

create index on public.products (seller_id);
create index on public.products (category_id);
create index on public.products (approval_status, status);
create index on public.messages (sender_id);
create index on public.messages (receiver_id);
create index on public.transactions (buyer_id);
create index on public.transactions (seller_id);
create index on public.reports (status);
create index on public.favorites (user_id);
